"""
用可视化方式说明负样本区分难度
"""
import numpy as np

def visualize_negative_difficulty():
    print("="*70)
    print("负样本区分难度可视化说明")
    print("="*70)
    
    print("\n【场景1：稀疏图 - 容易区分】")
    print("-"*70)
    print("图结构：")
    print("  节点: A, B, C, D, E, F, G, H, I, J")
    print("  边: A→B, C→D, E→F  (只有3条边，密度很低)")
    print()
    print("正样本: A→B (存在边)")
    print("  • 节点A和B有直接连接")
    print("  • 模型特征: [有边, 直接连接, 交互频繁]")
    print()
    print("负样本: G→H (不存在边)")
    print("  • 节点G和H没有连接")
    print("  • 节点G和H也没有共同邻居")
    print("  • 节点G和H特征差异大")
    print("  • 模型特征: [无边, 无连接, 无交互]")
    print()
    print("区分结果: ✓ 容易区分")
    print("  • 正样本特征: [1, 1, 1]  (有边, 有连接, 有交互)")
    print("  • 负样本特征: [0, 0, 0]  (无边, 无连接, 无交互)")
    print("  • 差异明显 → 模型容易学习 → AUC 高")
    
    print("\n【场景2：密集图 - 难以区分】")
    print("-"*70)
    print("图结构：")
    print("  节点: A, B, C, D, E, F")
    print("  边: A→B, A→C, A→D, B→C, B→D, C→D, E→F  (很多边，密度高)")
    print("  注意: A, B, C, D 之间几乎都有边，形成一个密集子图")
    print()
    print("正样本: A→B (存在边)")
    print("  • 节点A和B有直接连接")
    print("  • 节点A和B有共同邻居C和D")
    print("  • 模型特征: [有边, 直接连接, 有共同邻居, 交互频繁]")
    print()
    print("负样本: A→E (不存在边)")
    print("  • 节点A和E没有直接边")
    print("  • 但是：")
    print("    - 节点A连接了B, C, D")
    print("    - 节点E连接了F")
    print("    - 节点A和E的特征可能相似（都是活跃节点）")
    print("    - 节点A和E可能在未来会有边（只是现在没有）")
    print("  • 模型特征: [无边, 无直接连接, 但特征相似, 可能有关联]")
    print()
    print("区分结果: ✗ 难以区分")
    print("  • 正样本特征: [1, 1, 1, 1]  (有边, 有连接, 有共同邻居, 有交互)")
    print("  • 负样本特征: [0, 0, 1, 1]  (无边, 无直接连接, 但特征相似, 可能有关联)")
    print("  • 差异不明显 → 模型难以学习 → AUC 低")
    
    print("\n【关键理解】")
    print("-"*70)
    print("1. 负样本不是'完全随机'的节点对")
    print("   • 虽然随机采样，但采样的节点对可能有各种关联")
    print("   • 在密集图中，'不存在边'的节点对也可能很相似")
    print()
    print("2. 区分难度 = 正样本和负样本的'相似度'")
    print("   • 相似度高 → 难以区分 → 低AUC")
    print("   • 相似度低 → 容易区分 → 高AUC")
    print()
    print("3. 图密度影响相似度")
    print("   • 稀疏图：大部分节点对都不相似 → 负样本容易识别")
    print("   • 密集图：很多节点对都相似 → 负样本难以识别")
    
    print("\n【实际例子：Reddit数据集】")
    print("-"*70)
    print("从之前的分析：")
    print("  • 图密度: 6.83% (相对稀疏)")
    print("  • 难度等级: 中等")
    print("  • 这意味着：")
    print("    - 大部分节点对之间没有边")
    print("    - 负样本与正样本有一定差异")
    print("    - 模型可以较好地区分")
    print("    - 预期AUC可能在 0.80-0.90 之间")
    
    print("\n【对比：如果Reddit是密集图】")
    print("-"*70)
    print("假设图密度是 50%：")
    print("  • 大部分节点对之间都有边")
    print("  • 负样本（不存在的边）可能：")
    print("    - 节点特征相似")
    print("    - 有共同邻居")
    print("    - 在历史中曾经存在过")
    print("  • 模型难以区分 → 预期AUC可能在 0.65-0.75 之间")
    
    print("\n" + "="*70)
    print("总结：负样本区分难度 = 正负样本的相似程度")
    print("="*70)

if __name__ == "__main__":
    visualize_negative_difficulty()




