"""
详细解释负样本的区分难度为什么不同
"""
import numpy as np
import pandas as pd

def explain_negative_sample_difficulty():
    print("="*70)
    print("负样本区分难度详解")
    print("="*70)
    
    print("\n1. 什么是负样本？")
    print("-"*70)
    print("在链路预测任务中：")
    print("  • 正样本：数据集中实际存在的边（真实发生的交互）")
    print("  • 负样本：随机采样的节点对，这些节点对之间不存在边")
    print("  • 模型的任务：区分哪些节点对之间存在边（正样本），哪些不存在（负样本）")
    
    print("\n2. 负样本是如何生成的？")
    print("-"*70)
    print("从代码中可以看到，负样本通过 NegativeEdgeSampler 生成：")
    print("  • random 策略：随机选择源节点和目标节点，组成负样本边")
    print("  • 关键点：这些随机采样的节点对在数据集中不存在边")
    
    print("\n3. 为什么区分难度不同？")
    print("-"*70)
    
    print("\n【场景A：稀疏图（容易区分）】")
    print("假设：")
    print("  • 图有 10,000 个节点")
    print("  • 只有 10,000 条边（图密度 = 0.01%）")
    print("  • 这意味着大部分节点对之间都没有边")
    print("\n负样本特征：")
    print("  • 随机采样的负样本：节点A → 节点B（不存在边）")
    print("  • 这些节点对之间：")
    print("    - 没有直接连接")
    print("    - 可能也没有共同邻居")
    print("    - 节点特征可能差异很大")
    print("  • 模型很容易识别：'这两个节点之间没有边'")
    print("\n结果：")
    print("  ✓ 正样本（有边）和负样本（无边）差异明显")
    print("  ✓ 模型容易学习到区分模式")
    print("  ✓ AUC 可能较高（例如 0.95+）")
    
    print("\n【场景B：密集图（难以区分）】")
    print("假设：")
    print("  • 图有 1,000 个节点")
    print("  • 有 500,000 条边（图密度 = 50%）")
    print("  • 这意味着大部分节点对之间都有边")
    print("\n负样本特征：")
    print("  • 随机采样的负样本：节点C → 节点D（不存在边）")
    print("  • 但这些节点对之间：")
    print("    - 虽然没有直接边，但可能有共同邻居")
    print("    - 节点特征可能很相似")
    print("    - 在历史中可能曾经存在过边（后来删除了）")
    print("    - 节点之间可能只有'一步之遥'（通过一个中间节点连接）")
    print("  • 模型很难判断：'这两个节点之间真的没有边吗？'")
    print("\n结果：")
    print("  ✗ 正样本（有边）和负样本（无边）差异不明显")
    print("  ✗ 模型难以学习到清晰的区分模式")
    print("  ✗ AUC 可能较低（例如 0.70-0.80）")
    
    print("\n4. 具体例子")
    print("-"*70)
    
    print("\n例子1：社交网络（稀疏图）")
    print("  • 场景：Twitter 关注关系")
    print("  • 特征：")
    print("    - 用户A关注了用户B（正样本）")
    print("    - 用户C和用户D没有关注关系（负样本）")
    print("    - 用户C和用户D可能完全不认识，没有共同关注")
    print("  • 难度：容易区分")
    print("  • 原因：有边和没边的节点对差异很大")
    
    print("\n例子2：引用网络（密集图）")
    print("  • 场景：学术论文引用关系")
    print("  • 特征：")
    print("    - 论文A引用了论文B（正样本）")
    print("    - 论文C和论文D没有引用关系（负样本）")
    print("    - 但论文C和论文D可能：")
    print("      * 研究相同主题")
    print("      * 有共同作者")
    print("      * 引用相同的论文")
    print("      * 只是'恰好'没有直接引用")
    print("  • 难度：难以区分")
    print("  • 原因：有边和没边的节点对特征相似")
    
    print("\n5. 影响区分难度的因素")
    print("-"*70)
    print("1. 图密度")
    print("   • 密度越高，负样本越难区分")
    print("   • 因为密集图中，'不存在边'的节点对也可能很相似")
    
    print("\n2. 节点特征分布")
    print("   • 如果节点特征差异大，负样本容易区分")
    print("   • 如果节点特征相似，负样本难以区分")
    
    print("\n3. 图的演化模式")
    print("   • 如果图演化有规律，模型容易学习")
    print("   • 如果图演化随机，模型难以预测")
    
    print("\n4. 时间跨度")
    print("   • 时间跨度长：可能有更多历史信息帮助区分")
    print("   • 时间跨度短：信息不足，难以区分")
    
    print("\n6. 实际影响")
    print("-"*70)
    print("即使正负样本比例都是 1:1，但：")
    print("  • 稀疏图：负样本'明显不存在'，模型容易识别 → 高AUC")
    print("  • 密集图：负样本'看起来可能存在'，模型难以识别 → 低AUC")
    print("\n这就是为什么：")
    print("  • 相同模型在不同数据集上性能不同")
    print("  • 不是模型的问题，而是数据集本身的'难度'不同")
    
    print("\n7. 如何理解AUC的含义")
    print("-"*70)
    print("AUC = 模型能够正确区分正负样本的概率")
    print("  • AUC = 0.5：完全随机猜测（无法区分）")
    print("  • AUC = 1.0：完美区分（所有正样本得分都高于负样本）")
    print("\n在不同数据集上：")
    print("  • 稀疏图：AUC 0.95 可能意味着模型'很好地区分了明显的差异'")
    print("  • 密集图：AUC 0.75 可能意味着模型'在困难情况下仍能区分'")
    print("  • 因此，不能直接比较不同数据集上的AUC值")
    
    print("\n" + "="*70)
    print("总结：负样本区分难度取决于图的密度、节点特征、演化模式等因素")
    print("="*70)

if __name__ == "__main__":
    explain_negative_sample_difficulty()




